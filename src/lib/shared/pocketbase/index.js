import PocketBase from 'pocketbase';

// Адрес выбирается по месту запуска: браузер и скрипт живут в разных сетях.
// Браузер: тот же источник, где открыта страница, путь /api/pb/ — прокси nginx
// (nginx.conf.template). Раньше здесь было localhost:8090: он работал, только пока
// страница и база на одной машине. Если страница открыта с другого адреса, браузер
// идёт на порт 8090, туда не попадает, и проверка входа не проходит. Через прокси
// запрос идёт по тому же адресу, откуда приходит страница.
// Дев-сервер этот путь не знает, поэтому прокси /api/pb добавлен в vite.config.js.
// Node (пререндер при сборке и скрипты в контейнере): PB_URL, иначе localhost:8090.
// VITE_PB_URL задаёт адрес явно на этапе сборки — для случая, когда страница и база
// на разных источниках. Если переменная пустая, работает выбор по месту запуска.
const inBrowser = typeof window !== 'undefined' && typeof window.document !== 'undefined';

const PB_URL =
	import.meta.env?.VITE_PB_URL ||
	(inBrowser ? '/api/pb' : globalThis.process?.env?.PB_URL || 'http://localhost:8090');

const pb = new PocketBase(PB_URL);
pb.authStore.onChange(() => {});

// Auto-cancellation в SDK отменяет незавершённый запрос клиента, когда тем же клиентом
// проходит другой запрос. Клиент у нас один общий, а блоки читают его несколько раз
// подряд: замер 2026-11-10 — блок связей отправляет один и тот же фильтр дважды, и
// первый из двух одинаковых запросов season_carousel падает как net::ERR_ABORTED
// (ClientResponseError 0 «The request was autocancelled»). Запросы тут не мешают друг
// другу, их просто несколько, поэтому отмену отключаем.
//
// Чтобы не путать: страница /anime без параметра id висит на «Загрузка…» по другой
// причине — там просто нечего читать (id отсутствует), к отмене запросов это не
// относится; с id та же страница отвечает за один запрос.
pb.autoCancellation(false);

export default pb
