// того же дня: тайтл «Яга: Охота на ведьм» (номер Kinopoisk 13516692) не попал в ленту именно из-за
// порога 50 — при оценке TMDB 7.4 у него 18 голосов, то есть группа 4, и при полном пуле такая
// группа пропускается. У новой премьеры голосов физически не может быть 50: за тридцать дней
// тайтл не набирает столько, и лента набиралась бы только старыми тайтлами с большим числом
// голосов. Поэтому внутри окна хватает 10 голосов, а для тайтлов вне окна порог остаётся 50.
const QUALITY_MIN_VOTES_FRESH = 10;
const MYSHOWS_SCALE = 2;          // пятибалльная шкала myshows -> десятибалльная

// Порог свежести для группы порога. Порог оценки говорит о качестве, но не о том, интересен ли
// тайтл сегодня: окно Kodik сортируется по updated_at, и в него попадают сериалы 1990–2018 годов,
// у которых вышла серия. Замер снимка 2026-11-06: 11 карточек, шесть из них старше 2020 года
// (1990, 1999, 2005, 2007, 2015, 2018) — оценки у них 8.0–8.8, то есть порог они проходят, но
// лента по этому и выглядела «старой». Поэтому группа порога делится на свежую и старую, и по
// решению 2026-11-06 порядок такой: топ-100, свежие по порогу, старые по порогу, заполнение.
const FRESH_YEAR = 2020;

// Группа качества кандидата:
//   1 — имя есть в топ-100 популярного сейчас;
//   2 — оценка не ниже порога при достаточном числе голосов, год не старше FRESH_YEAR;
//   3 — оценка не ниже порога, но год старше FRESH_YEAR;
//   4 — низкая оценка или оценки нет.
// Четвёртую группу не отвергаем всегда: по замеру того же дня она оставила бы ленту почти пустой
// (в топ-100 только 6 тайтлов окна из 111 строк myshows), поэтому она работает заполнением —
// см. отбор ниже, где она пускается только когда тайтлов порога хватило бы на всю карусель.
function qualityTier(candidate, top) {
	const key = candidate.patch?.nameKey || nameKeyOf(candidate.patch?.title);
	const orig = nameKeyOf(candidate.patch?.titleOrig);

	if (top.has(key) || (orig && top.has(orig))) return 1;

	const raw = Number(candidate.patch?.rating);

	if (!Number.isFinite(raw) || raw <= 0) return 4;

	// Оценка уже приведена к десятибалльной шкале при сборе кандидата (myshows пересчитан),
	// поэтому здесь порог сравнивается с ним как есть.
	const rating = raw;
	// Голоса: Number(null) даёт 0, и карточка без голосов (строка Kodik, перенесённая запись, где
	// поле голосов в базе нет) не прошла бы порог, хотя правило требует только оценку. Поэтому
	// отсутствие голосов считаем отдельно, а не как ноль.
	const votes = candidate.votes === null || candidate.votes === undefined ? null : Number(candidate.votes);

	// Порог голосов зависит от того, премьера ли тайтл внутри окна (см. QUALITY_MIN_VOTES_FRESH).
	// Голосов у части источников нет (у строки Kodik оценки есть, голоса нет): тогда качество
	// решает только сама оценка.
	if (rating >= QUALITY_MIN_RATING && (votes === null || votes >= (candidate.premiere ? QUALITY_MIN_VOTES_FRESH : QUALITY_MIN_VOTES))) {
		// Год неизвестный (источник не ответил годом) не считаем свежим: такую строку пускаем
		// только после свежих, как старую.
		return Number(candidate.patch?.year) >= FRESH_YEAR ? 2 : 3;
	}

	return 4;
}

