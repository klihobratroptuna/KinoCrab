function usablePoster(url) {
	const raw = clean(url);

	if (!/^https?:\/\//i.test(raw)) return '';

	// Заглушка «постера» не постер: Kinopoisk отдаёт no-poster.png по любому адресу, где
	// картинки нет, и по номеру тоже. Замер 2026-11-05:
	//   st.kp.yandex.net/images/film_big/no-poster.png → 200, image/gif, 2401 байт, 208×304;
	//   st.kp.yandex.net/images/film_big/11312133.jpg → тот же файл, те же 2401 байт.
	// Настоящий постер с этого CDN — jpeg и от 60 КБ (замер 5505084.jpg: 96624 байта).
	// Поэтому адрес заглушки не принимаем, и путь идёт к следующему источнику.
	if (/no-poster/i.test(raw)) return '';

	const host = hostOf(raw);

	if (!host || BLOCKED_POSTER_HOSTS.has(host)) return '';

	return raw;
}

// Первый жанр строки. Лента Kodik отдаёт жанры списком строк (замер 2026-11-05: all_genres
// ["драма","триллер","мистика","медицина"]), а ответ myshows — списком объектов
// {id, title, alias}. Проверено 2026-11-05: на всех карточках снимка «Сериалы» в строке под
// названием печаталось "[object Object]" — clean() превращает объект в такое слово, а блок
// выводит поле как есть. Причина была в модуле myshows (там жанр брали из genres[0] напрямую);
// здесь объект разбираем по именам, которые встречаются в ответах: title, genre, name.
function firstGenre(value) {
	if (Array.isArray(value)) {
		const first = value[0];

		if (first && typeof first === 'object') return clean(first.title || first.genre || first.name);

		return clean(first);
	}

	const text = clean(value);

	return text ? clean(text.split(',')[0]) : '';
}

// Полный список жанров строки источника: Kodik отдаёт жанры списком строк, ответ myshows —
// списком объектов {id, title, alias}, ответ TMDB — списком id, которые мы превращаем в имена.
// Правило про мультипликационные сериалы обязано смотреть на весь список: по первому жанру такой
// тайтл не опознать. Замер 2026-11-06 по карточке «Леди Баг и Супер-кот»: первый жанр строки
// myshows — «Боевик», полный список — «Боевик, Детский, Комедия», категория строки — show.
function genreList(value) {
	if (Array.isArray(value)) {
		return value.map((item) => (item && typeof item === 'object' ? clean(item.title || item.genre || item.name) : clean(item))).filter(Boolean);
	}

	const text = clean(value);

	return text ? text.split(',').map((part) => clean(part)).filter(Boolean) : [];
}

