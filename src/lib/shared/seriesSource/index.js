function byPriority(a, b) {
	const pa = russianName(a.title) ? 0 : 1;
	const pb = russianName(b.title) ? 0 : 1;

	if (pa != pb) return pa - pb;

	return a.windowDay < b.windowDay ? 1 : a.windowDay > b.windowDay ? -1 : 0;
}

