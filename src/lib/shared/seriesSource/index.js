const ANIMATION_GENRES = new Set([
	'мультсериал',
	'мультсериалы',
	'мультфильм',
	'мультфильмы',
	'мультипликация',
	'анимация',
	'аниме',
	'animation',
	'cartoon',
	'anime',
	'animated'
]);

function isAnimation(candidate) {
	const list = Array.isArray(candidate?.genres) ? candidate.genres : [];

	for (const genre of list) {
		if (ANIMATION_GENRES.has(String(genre).toLowerCase())) return true;
	}

	return ANIMATION_GENRES.has(String(candidate?.category || '').toLowerCase());
}

function normalizeLink(link) {
	if (!link) return '';

	return link.startsWith('//') ? `https:${link}` : link;
}

// Строка серий в том же виде, что пишет карусель дорам: «1-12 Серия из 21».
function episodeOf(row, data) {
	const episode = clean(row.last_episode);
	const season = clean(row.last_season);
	const total = clean(data.episodes_total || row.episodes_count);

	if (!episode) return '';

	const shown = total || episode;

	return season ? `${season}-${episode} Серия из ${shown}` : `Серия ${episode} из ${shown}`;
}

// День окна по строке источника. Kodik отдаёт метки времени в UTC, а карусель живёт по
// Москве (правило moscowDate), поэтому дата считается по московскому числу этого момента.
function dayOf(value) {
	const raw = String(value || '');

	if (!raw) return '';

	const date = new Date(raw);

	return Number.isFinite(date.getTime()) ? todayKey(date) : keyOf(raw);
}

export function windowKeys(now = new Date()) {
	const day = todayKey(now);

	return { day, back: addDaysKey(day, -NOVINKI_DAYS), forward: day };
}

function inWindow(key, keys) {
	return Boolean(key) && key >= keys.back && key <= keys.forward;
}

// Имена, которые карусель дорам показывает сейчас: группа самого свежего дня, та же, что
// берёт блок dramaCarousel. Сравниваем имя целиком и короткое имя без суффикса сезона:
// дорамы называют тайтл «Баларао 1 Сезон (2026)», а строка Kodik — просто «Баларао».
// Список держим в памяти два минуты — как кэш снимка, чтобы не читать коллекцию на каждый
// показ; записью дорамы обновляются тем же проходом, что и карусель дорам.
let dramaKeys = null;
let dramaKeysAt = 0;

async function dramaShownKeys(force = false) {
	if (!force && dramaKeys && Date.now() - dramaKeysAt < 120000) return dramaKeys;

	const records = await pb
		.collection(DRAMA_COLLECTION)
		.getFullList({ sort: '-day, pos', perPage: SNAPSHOT_PAGE })
		.catch(() => []);

	const keys = new Set();

	if (records.length) {
		const newest = records[0].day;

		for (const record of records) {
			if (record.day != newest) continue;

			const full = nameKeyOf(record.title);

			if (!full) continue;

			keys.add(full);
			keys.add(shortNameOf(record.title));
		}
	}

	dramaKeys = keys;
	dramaKeysAt = Date.now();

	return keys;
}

function inDrama(keys, name) {
	return keys.has(name) || keys.has(shortNameOf(name));
}

// День, к которому относится карточка: поступление в Kodik, иначе мировая премьера, иначе
// обновление записи — это значит, что за окно вышла новая серия. Всё это в той же строке
// списка. Строка источника берётся из ответа Kodik, поэтому и дата берётся из той строки;
// для строк TMDB день считается отдельно, по first_air_date.
function windowDayOf(row, keys) {
	const data = row.material_data || {};

	const created = dayOf(row.created_at);

	if (created && inWindow(created, keys)) return created;

	const premiere = dayOf(data.premiere_world);

	if (premiere && inWindow(premiere, keys)) return premiere;

	const updated = dayOf(row.updated_at);

	if (updated && inWindow(updated, keys)) return updated;

	return '';
}

// Премьера ли тайтл внутри окна — от этого зависит порог голосов (QUALITY_MIN_VOTES_FRESH).
// У строки Kodik дата премьеры есть: material_data.premiere_world, а created_at — дата
// появления записи, то есть дата премьеры сезона. У строки TMDB премьера внутри окна по
// построению пути (first_air_date.gte/lte), поэтому там признак ставится в windowCandidates.
// У строки календаря myshows дата — выход конкретной серии, а не премьера шоу: девяносто
// серий за окно у шоу 2015 года не делают его премьерой, поэтому там признак всегда false и
// порог голосов остаётся 50.
function premiereOfKodik(row, keys) {
	const premiere = dayOf(row.material_data?.premiere_world);

	if (premiere && inWindow(premiere, keys)) return true;

	const created = dayOf(row.created_at);

	return Boolean(created && inWindow(created, keys));
}

// Токен подставляет nginx (KODIK_TOKEN): в браузере его показывать нельзя.
// Сортировка created_at даёт новые записи, updated_at — записи, которые обновили за окно,
// то есть шоу с новой серией за окно. Параметр countries= принимает одно значение: список
// стран через запятую или через вертикальную черту не работает — «США,Германия» отвечает так
// же, как одно «США» (total 48), а «США|Германия» отвечает пустым (total 0). Проверено живым
// замером 2026-11-04, поэтому каждая страна запрашивается отдельно. Параметр country=
// не фильтрует.
function feedPath(limit, opts = {}) {
	const params = new URLSearchParams({
		types: opts.types || TYPES,
		limit: String(limit),
		sort: opts.sort || 'created_at',
		order: 'desc',
		with_material_data: '1'
	});

	if (opts.country) params.set('countries', opts.country);

	return `/api/kodik/list?${params}`;
}

async function kodikRows(limit, opts = {}) {
	const path = feedPath(limit, opts);
	const answer = await netCache(`kodik:feed:series:${path}`, () => netFetch(path, { timeoutMs: 15000, attempts: 3 }));

	if (!answer.ok) return { ok: false, reason: netSummary('Kodik', answer), rows: [] };

	// Массив строк в ответе list называется results, а не items.
	return { ok: true, reason: '', rows: answer.data?.results || [] };
}

function patchFor(row, name, day) {
	const data = row.material_data || {};
	const title = clean(data.title || row.title);
	const poster = usablePoster(data.poster_url) || usablePoster(data.drama_poster_url);
	const rating = numberRating(data.mydramalist_rating);

	return {
		day,
		pos: 0,
		nameKey: name,
		windowDay: '',
		title,
		// Оригинальное имя из строки Kodik. Его сохраняем, потому что поиск TMDB не находит
		// шоу по русскому переводу, но находит по оригинальному имени, и это имя нужно
		// карточке и в следующие сутки, когда её переносит перенос из снимка предыдущего дня.
		titleOrig: clean(row.title_orig || row.other_title || data.title_en),
		// Страна строки Kodik — она же решает, показывать карточку в этой вкладке.
		country: countriesOf(data.countries).join(', '),
		year: clean(row.year || String(data.year || '')),
		genre: firstGenre(data.all_genres || data.genres),
		rating: rating != null ? String(rating) : '',
		episode: episodeOf(row, data),
		poster,
		kinopoiskId: clean(row.kinopoisk_id || data.kinopoisk_id),
		imdbId: clean(row.imdb_id || data.imdb_id),
		kodikId: isKodikId(row.id) ? row.id : '',
		// Строка списка Kodik — это запись с плеером: по её id страница /watch собирает кадр.
		player: isKodikId(row.id),
		via: 'kodik',
		sourceUrl: normalizeLink(row.link),
		checkNote: '',
		checkDay: ''
	};
}

// Карточка, которая пришла не из строки Kodik (по имени или записью календаря): плеера у
// неё нет, и проверка подтверждает, что он появился. Такие карточки доходят из проходов,
// где тайтл знали только по имени, и остаются в окне, пока их день окна внутри ±7 дней.
// Перенос записки previous дня в patch текущего дня. Проверено 2026-11-06: поле genre у
// перенесённой записки остаётся как было, то есть записанное раньше "[object Object"]
// переживает перенос — починить его можно только когда тайтл снова проверится от источника
// и значение пересоберётся из ответа. Поэтому чиним источник, а не перенос.
