// Нормализация имени для сопоставления тайтлов. Держим это в отдельном файле без импорта
// PocketBase, чтобы проверку можно было прогнать на живых данных: в Node импорт `$lib` не
// работает, поэтому чистые модули (как animevost/parse.js) проверяются напрямую.

/** Название для сравнения: без регистра и пунктуации, как в скрапере дорам. */
export function nameKeyOf(value) {
	return String(value || '')
		.toLowerCase()
		.replace(/[^\p{L}\p{N}]+/gu, ' ')
		.replace(/\s{2,}/g, ' ')
		.trim();
}

// Имя карточки карусели без суффикса сезона и года в скобках: в календаре тайтл хранится
// коротким именем. Границу \b не используем — в JavaScript она работает только для
// [A-Za-z0-9_], после кириллического «сезон» её нет.
//
// Сезон словами добавлен 2026-11-05: онгоинги animevost пишут «Сасаки и Пи (второй сезон)»,
// и такой суффикс числом не является. Замер на живых записях дня: по полному имени находилось
// 12 карточек из 20, с сезоном словами — 17 из 20 (карточки 1, 2, 7, 11, 19), и запрос к
// Shikimori оставался только для 2 тайтлов.
//
// Что здесь надо помнить: короткое имя — одно значение, и на один тайтл календарь может
// хранить записи разных сезонов; берётся самая свежая. Это тот же тайтл, но сезон может
// быть не тот, и так было уже с числовым суффиксом — слова добавили 5 карточек из 20.
const SEASON_WORDS_RE =
	/\s+(первый|второй|третий|четвёртый|пятый|шестой|седьмой|восьмой|девятый|десятый|second|third|fourth|fifth|sixth)\s+(сезон|сезоны|season|seasons)$/gu;

export function shortNameOf(value) {
	return nameKeyOf(value)
		.replace(/\s+\d{4}$/gu, '')
		.replace(/\s+\d{1,2}\s+(сезон|сезоны|season|seasons)$/gu, '')
		.replace(SEASON_WORDS_RE, '')
		.replace(/\s{2,}/g, ' ')
		.trim();
}
