// Кэш снимков каруселей в памяти на несколько минут.
//
// Почему это нужно: каждый показ карусели читал PocketBase. Блок на главной читает
// снимок при появлении, потом читает его ещё раз после суточного обновления, а при
// переходе между вкладками «Фильмы / Аниме / Дорамы» каждый блок появляется заново —
// то есть три чтения на один просмотр страницы. Снимок меняется один раз в сутки,
// поэтому повторные чтения за несколько минут можно отдавать из памяти: источник и
// база при этом не затрагиваются, показ остаётся ровно тот же.
//
// После суточного обновления кэш обязательно заполняется записями, которые только что
// легли в базу (функции refresh читают снимок с force), поэтому минуты кэша не означают,
// что карусель показывает старый снимок.
//
// Только память браузера: на сервере каруселей нет, и кэш между запросами здесь был бы
// неуместен (разные посетители видят разное).
import { browser } from '$app/environment';

const TTL_MS = 120000;

const store = new Map();

/**
 * value = результат loader(). Если запись свежая — возвращаем её, иначе читаем и
 * запоминаем. force нужен после записи в базу: читать нужно обязательно, иначе
 * карусель показала бы снимок до обновления.
 */
export async function readSnapshot(key, loader, force = false) {
	if (!browser) return loader();

	const hit = store.get(key);

	if (!force && hit && Date.now() - hit.at < TTL_MS) return hit.value;

	const value = await loader();

	if (value) store.set(key, { at: Date.now(), value });

	return value;
}

export function clearSnapshot(key) {
	store.delete(key);
}
